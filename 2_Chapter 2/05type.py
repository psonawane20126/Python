a = 31
t = type(a) # class 'int' is the data type of a
print(t)

b = 5.22
u = type(b) # class 'float' is the data type of b
print(u)

# we can change data type from one to another
c = "32.2" # c is string data type
d = float(c) # here we are converting string data type to float data type
v = type(d) # class 'float' is the data type of d
print(v) 

# a number can be converted into string and vice versa (if possible)
# there are many functions to convert data type from one to another like int(), float(), str(), bool() etc.
