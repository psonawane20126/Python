# Arithmetic Operators

a = 10

b = 5

print(a + b) # Addition


# Assignment Operators
a = 4 - 2 # here a is assigned the value of 4 - 2
print(a)

b = 6 
b-= 3 # here b is assigned the value of b - 3
print(b)


# Comparision Operators

d = 4 > 5 
print(d)

#logical Operators
e = True or False
print(e)

# Truth Table for AND operator
print(True and True) # True
print(True and False) # False   
print(False and True) # False
print(False and False) # False

#truth Table for OR operator
print(True or True) # True
print(True or False) # True
print(False or True) # True
print(False or False) # False
 
  
# Truth Table for NOT operator
print(not True) # False 
print(not False) # True

# truth Table for XOR operator
print(True ^ True) # False
print(True ^ False) # True
print(False ^ True) # True
print(False ^ False) # False

# truth table for NOR operator
print(not (True or True)) # False
print(not (True or False)) # False
print(not (False or True)) # False
print(not (False or False)) # True
